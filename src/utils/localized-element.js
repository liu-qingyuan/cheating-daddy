export function setInterfaceLanguage(language) {
    document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
    window.dispatchEvent(new Event('interface-language-changed'));
}
// Only UI copy is translated. Never translate question text, transcripts or model answers.
export class LocalizedElement extends LitElement {
    static properties = { uiLanguage: { state: true } };
    constructor() {
        super();
        this.uiLanguage = document.documentElement.lang === 'en' ? 'en' : 'zh-CN';
        this._languageChanged = () => {
            this.uiLanguage = document.documentElement.lang === 'en' ? 'en' : 'zh-CN';
        };
    }
    connectedCallback() {
        super.connectedCallback();
        window.addEventListener('interface-language-changed', this._languageChanged);
        this._languageChanged();
    }
    disconnectedCallback() {
        window.removeEventListener('interface-language-changed', this._languageChanged);
        super.disconnectedCallback();
    }
    t(text) {
        return (this.uiLanguage === 'en' ? english : chinese)[text] ?? text;
    }
}
